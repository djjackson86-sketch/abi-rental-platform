# ── Helpers (mirrors saDiscParser.ts:78-166) ────────────────────────────────


def normalise_date(value: str) -> str:
    """``20270331`` / ``2027-03-31`` / ``31/03/2027`` -> ``2027-03-31``; else ``''``."""
    text = (value or "").strip()
    for pattern, fmt in DATE_FORMATS:
        match = pattern.match(text)
        if match:
            return fmt(match)
    return ""


def is_plausible_date(iso: str, *, now_year: int | None = None) -> bool:
    """The reference guards against mis-reading numbers as dates: year within now-5..now+15
    and a real month."""
    if not iso or len(iso) < 7:
        return False
    try:
        year = int(iso[0:4])
        month = int(iso[5:7])
    except ValueError:
        return False
    current = now_year if now_year is not None else datetime.now().year
    return (current - 5) <= year <= (current + 15) and 1 <= month <= 12


def find_date(tokens: Sequence[str], *, now_year: int | None = None) -> str:
    """Any plausible date in the tokens; the **latest** one wins (issue vs expiry)."""
    dates: list[str] = []
    for token in tokens:
        parsed = normalise_date(token)
        if parsed and is_plausible_date(parsed, now_year=now_year):
            dates.append(parsed)
    for token in tokens:
        match = _LOOSE_DATE_RE.search(token)
        if match:
            candidate = f"{match.group(1)}-{match.group(2)}-{match.group(3)}"
            if is_plausible_date(candidate, now_year=now_year) and candidate not in dates:
                dates.append(candidate)
    if dates:
        return sorted(dates)[-1]
    return ""


def find_make(tokens: Sequence[str]) -> tuple[str, int]:
    """First known make in the tokens, or a two-token compound (``LAND ROVER``)."""
    for index, token in enumerate(tokens):
        upper = token.upper().strip()
        if upper in KNOWN_MAKES:
            return upper, index
        if index + 1 < len(tokens):
            compound = f"{upper} {tokens[index + 1].upper().strip()}"
            if compound in KNOWN_MAKES:
                return compound, index
    return "", -1


def find_colour(tokens: Sequence[str]) -> str:
    for token in tokens:
        upper = token.upper().strip()
        if upper in KNOWN_COLOURS:
            return upper
    return ""


def find_vehicle_type(tokens: Sequence[str]) -> str:
    for token in tokens:
        upper = token.upper().strip()
        if upper in VEHICLE_TYPES:
            return upper
    raw = " ".join(tokens).upper()
    for vehicle_type in VEHICLE_TYPES:
        if vehicle_type in raw:
            return vehicle_type
    return ""


def find_masses(tokens: Sequence[str]) -> tuple[str, str]:
    """``(gross, tare)`` — the reference assumes the heaviest number is the GVM."""
    masses: list[int] = []
    for token in tokens:
        match = _MASS_TOKEN_RE.match(token.strip())
        if match:
            value = int(match.group(1))
            if _MIN_MASS_KG <= value <= _MAX_MASS_KG:
                masses.append(value)
    masses.sort(reverse=True)
    gross = str(masses[0]) if len(masses) > 0 else ""
    tare = str(masses[1]) if len(masses) > 1 else ""
    return gross, tare


def is_vin(value: str) -> bool:
    return bool(VIN_RE.search(value.strip()))


# ── Real modern disc layout (measured, positional) ──────────────────────────

#: The 2026 sample disc decodes to a `%`-delimited record whose field ORDER carries the meaning —
#: there are no labels and no `|`/newline separators to sniff, so the heuristic passes below
#: cannot be trusted to place every field. Measured on the real payload:
#:   %MVL1CC53%0148%4522A001%1%4024048GB8LY%KP35XKGP%SHS812W%Station wagon / Stasiewa%
#:   MITSUBISHI%ASX%White / Wit%JMYXTGA2WDZ000956%4B11LC0187%2027-07-31%
#: split('%') -> [ '', 'MVL1CC53', '0148', '4522A001', '1', then the fields below ]
#: Only the unambiguous fields are taken here. The three identifier fields (5/6/7) are left to
#: the generic pass plus review: which of them is the NaTIS registration number and which the
#: licence number (plate) has NOT been confirmed against a full printed disc face, and D3 forbids
#: guessing. `MVL1CC53` (the form identifier) is likewise not a vehicle figure.
POSITIONAL_FORM_PREFIX = "%MVL"
_POSITIONAL_MIN_FIELDS = 16
POSITIONAL_TYPE_INDEX = 8
POSITIONAL_MAKE_INDEX = 9
POSITIONAL_MODEL_INDEX = 10
POSITIONAL_COLOUR_INDEX = 11
POSITIONAL_VIN_INDEX = 12
POSITIONAL_ENGINE_INDEX = 13
POSITIONAL_EXPIRY_INDEX = 14
POSITIONAL_IDENTIFIER_INDEXES = (5, 6, 7)


def _first_dual_language_part(value: str) -> str:
    """``"Station wagon / Stasiewa"`` -> ``"Station wagon"`` (the disc prints EN / AF)."""
    return value.split("/")[0].strip()


def parse_natis_positional(raw: str) -> dict[str, str] | None:
    """Parse the modern positional NaTIS layout, or ``None`` if this is not that layout.

    The record is self-describing in one useful way — field 2 is its own length:

        %MVL1CC53%0148%...    ->  0148 == len(payload) == 148

    That self-check is what makes it safe to treat the layout as positional at all, and it is the
    first thing a piece of corrupt data fails. Three driver's-licence samples and every older
    "label-value" / delimited disc keep working through the heuristic passes below.
    """
    if not raw.startswith(POSITIONAL_FORM_PREFIX):
        return None
    fields = raw.split("%")
    if len(fields) < _POSITIONAL_MIN_FIELDS:
        return None

    declared_length = fields[2]
    if not declared_length.isdigit() or int(declared_length) != len(raw.strip()):
        return None

    vin = fields[POSITIONAL_VIN_INDEX].strip().upper()
    if not re.fullmatch(r"[A-HJ-NPR-Z0-9]{17}", vin, re.ASCII):
        return None

    expiry = normalise_date(fields[POSITIONAL_EXPIRY_INDEX])
    if not expiry:
        return None

    result = {
        "vehicleType": _first_dual_language_part(fields[POSITIONAL_TYPE_INDEX]).upper(),
        "make": fields[POSITIONAL_MAKE_INDEX].strip().upper(),
        "model": fields[POSITIONAL_MODEL_INDEX].strip(),
        "colour": _first_dual_language_part(fields[POSITIONAL_COLOUR_INDEX]).upper(),
        "vin": vin,
        "engineNumber": fields[POSITIONAL_ENGINE_INDEX].strip().upper(),
        "expiryDate": expiry,
        "positionalIdentifiers": [
            fields[index].strip() for index in POSITIONAL_IDENTIFIER_INDEXES if fields[index].strip()
        ],
    }
    return result


