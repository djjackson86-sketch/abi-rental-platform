# ── Errors ──────────────────────────────────────────────────────────────────


class DiscErrorKind:
    """Distinct failure kinds — the scan UI must tell these apart (A1 spec step 4)."""

    NO_BARCODE = "no_barcode"
    """Nothing decoded: no PDF417 found in any image variant (or no engine installed)."""

    UNPARSEABLE = "unparseable"
    """A barcode decoded, but the payload yielded no recognisable disc field."""

    IMAGE_UNREADABLE = "image_unreadable"
    """The bytes were not a readable image."""


class DiscDecodeError(Exception):
    """Raised when a disc image cannot be turned into fields.

    ``kind`` is one of :class:`DiscErrorKind` so callers can show the right message: "we could
    not find a barcode on that photo — try again flatter/closer" reads very differently from
    "we found the barcode but could not read the fields off it".
    """

    def __init__(self, kind: str, message: str = "", *, detail: str = ""):
        super().__init__(message or kind)
        self.kind = kind
        self.detail = detail

    def __str__(self) -> str:  # pragma: no cover - trivial
        return f"{self.kind}: {super().__str__()}"


