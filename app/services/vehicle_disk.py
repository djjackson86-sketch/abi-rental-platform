def parse_labelled_fields(raw: str) -> dict[str, str]:
    result = dict(_LABEL_DEFAULTS)
    for key, pattern in _LABEL_PATTERNS:
        if result[key]:
            continue
        match = pattern.search(raw)
        if match:
            value = match.group(1).strip()
            if key == "expiryDate":
                value = normalise_date(value) or value
            if value:
                result[key] = value
    if not result["licenceNumber"] and result["registerNumber"]:
        result["licenceNumber"] = result["registerNumber"]
    return result


# ── Percent-delimited parsing (mirrors saDiscParser.ts:235-273) ─────────────


def parse_percent_delimited(raw: str) -> dict[str, str] | None:
    if "%" not in raw:
        return None
    fields = [part.strip() for part in raw.split("%")]
    if len(fields) < 8:
        return None

    result: dict[str, str] = {}
    for field in fields:
        if not field:
            continue
        if VIN_RE.search(field) and not result.get("vin"):
            result["vin"] = VIN_RE.search(field).group(1)  # type: ignore[union-attr]
            continue
        if PLATE_RE.search(field) and not result.get("licenceNumber"):
            result["licenceNumber"] = field
            continue
        if field.upper() in KNOWN_MAKES and not result.get("make"):
            result["make"] = field.upper()
            continue
        if field.upper() in KNOWN_COLOURS and not result.get("colour"):
            result["colour"] = field.upper()
            continue
        parsed_date = normalise_date(field)
        if parsed_date and is_plausible_date(parsed_date):
            existing = result.get("expiryDate")
            if not existing or parsed_date > existing:
                result["expiryDate"] = parsed_date
            continue
        if _PLAIN_MASS_RE.match(field):
            value = int(field)
            if _MIN_MASS_KG <= value <= _MAX_MASS_KG:
                if not result.get("tare"):
                    result["tare"] = field
                    continue
                if not result.get("grossMass"):
                    result["grossMass"] = field
                    continue
        if (
            _ALNUM6_15_RE.match(field)
            and _HAS_LETTER_RE.search(field)
            and _HAS_DIGIT_RE.search(field)
            and not is_vin(field)
            and not result.get("engineNumber")
        ):
            result["engineNumber"] = field

    return result if any(result.values()) else None


# ── Main entry (mirrors saDiscParser.ts:277-379) ────────────────────────────


def _token_list(raw: str) -> list[str]:
    return [token.strip() for token in TOKEN_SPLIT_RE.split(raw) if token.strip()]


# A token is "recognised" when it carries some signal the parser understands: a label keyword,
# a date, a number, a known make/colour/type, or text that ended up in a parsed field. Tokens
# with none of that are surfaced in ``unparsed_fields`` so staff can eyeball them. Purely
# cosmetic — it never feeds a parsed field, so it cannot shift parity with the reference.
_RECOGNISED_HINT_RE = re.compile(
    r"licence|license|lisensie|number\s*plate|plate|register|control|make|model|series|"
    r"description|vin|identification|engine|expir|tare|gvm|mass|colou?r|category|type|date",
    re.ASCII | re.IGNORECASE,
)
_ANY_DATE_RE = re.compile(
    r"\d{4}[/\-.]\d{2}[/\-.]\d{2}|\d{2}[/\-.]\d{2}[/\-.]\d{4}|\d{8}", re.ASCII
)
_CONTAINMENT_KEYS = (
    "vin",
    "engine_number",
    "licence_number",
    "make",
    "model",
    "colour",
    "vehicle_type",
    "registering_authority",
    "control_number",
    "registration_number",
)


def _token_is_recognised(token: str, parsed: Mapping[str, Any]) -> bool:
    stripped = token.strip()
    if not stripped:
        return True
    upper = stripped.upper()
    if upper in KNOWN_MAKES or upper in KNOWN_COLOURS or upper in VEHICLE_TYPES:
        return True
    if _RECOGNISED_HINT_RE.search(stripped):
        return True
    if _ANY_DATE_RE.search(stripped) or _HAS_DIGIT_RE.search(stripped):
        return True
    for key in _CONTAINMENT_KEYS:
        value = str(parsed.get(key) or "").strip()
        if len(value) >= 3 and value.upper() in upper:
            return True
    return False


def _explained_token_indexes(
    tokens: Sequence[str], raw: str, parsed: Mapping[str, Any]
) -> set[int]:
    return {index for index, token in enumerate(tokens) if _token_is_recognised(token, parsed)}


def _mass_to_float(value: str) -> float | None:
    """Blank -> ``None`` (never 0), and out-of-range -> ``None``.

    ABI safety guard, the one place this module is stricter than the reference: the reference's
    *label-value* mass regexes accept any 3-5 digit run with no range check, so a garbage
    payload can yield a nonsense figure (measured: ``GVM 1234567`` -> ``12345``). Decision D3 is
    "never invent a vehicle figure", so anything outside the physical 300-80000 kg window is
    dropped instead of stored. This can only ever blank a value, never produce one.
    """
    try:
        number = float(str(value).strip())
    except (TypeError, ValueError):
        return None
    if not (_MIN_MASS_KG <= number <= _MAX_MASS_KG):
        return None
    return number


def parse_disc_text(raw: str) -> dict[str, Any]:
    """Parse a decoded disc payload into ABI's field names.

    Never raises: junk in gives empty fields, ``confidence == 'low'`` and the verbatim text
    back, so the scan screen can always fall back to manual entry.
    """
    raw = raw or ""

    # ── Phase 0: the modern positional layout, when the record proves it is one ──
    positional = parse_natis_positional(raw) or {}

    # ── Phase 1: label-value, then percent-delimited ──
    labelled = parse_labelled_fields(raw)
    percent = parse_percent_delimited(raw) or {}

    # ── Phase 2: token pattern matching ──
    tokens = _token_list(raw)

    vin_match = VIN_RE.search(raw)
    plate_match = PLATE_RE.search(raw)
    token_make, make_index = find_make(tokens)
    token_colour = find_colour(tokens)
    token_vehicle_type = find_vehicle_type(tokens)
    token_expiry_date = find_date(tokens)
    gross_mass_token, tare_token = find_masses(tokens)

    token_model = ""
    if token_make and make_index >= 0 and make_index + 1 < len(tokens):
        following = tokens[make_index + 1].strip()
        if (
            following.upper() not in KNOWN_COLOURS
            and following.upper() not in VEHICLE_TYPES
            and not VIN_RE.search(following)
            and not normalise_date(following)
        ):
            token_model = following

    token_engine_number = ""
    if vin_match:
        vin_index = raw.find(vin_match.group(1))
        after_vin = raw[vin_index + 17 : vin_index + 50].strip()
        engine_match = re.match(r"[\s|;%\n\r]*([A-Z0-9]{5,15})", after_vin, re.ASCII)
        if engine_match:
            token_engine_number = engine_match.group(1)
    if not token_engine_number:
        for token in tokens:
            trimmed = token.strip()
            if (
                _ENGINE_TOKEN_RE.match(trimmed)
                and _HAS_LETTER_RE.search(trimmed)
                and _HAS_DIGIT_RE.search(trimmed)
                and not is_vin(trimmed)
                and not PLATE_RE.search(trimmed)
                and trimmed not in KNOWN_MAKES
                and trimmed not in KNOWN_COLOURS
            ):
                token_engine_number = trimmed
                break

    token_vin = vin_match.group(1) if vin_match else ""
    token_plate = re.sub(r"\s+", " ", plate_match.group(1)).strip() if plate_match else ""

    # ── Phase 3: merge — positional > label-value > percent > token ──
    vin = positional.get("vin") or labelled["vin"] or percent.get("vin") or token_vin
    plate = labelled["licenceNumber"] or percent.get("licenceNumber") or token_plate
    make = positional.get("make") or labelled["make"] or percent.get("make") or token_make
    model = positional.get("model") or labelled["model"] or percent.get("model") or token_model
    engine_number = (
        positional.get("engineNumber")
        or labelled["engineNumber"]
        or percent.get("engineNumber")
        or token_engine_number
    )
    expiry_candidates = [
        candidate
        for candidate in (
            positional.get("expiryDate"),
            labelled["expiryDate"],
            percent.get("expiryDate"),
            token_expiry_date,
        )
        if candidate
    ]
    expiry_date = max(expiry_candidates) if expiry_candidates else ""
    tare = labelled["tare"] or percent.get("tare") or tare_token
    gvm = labelled["grossMass"] or percent.get("grossMass") or gross_mass_token
    colour = (
        positional.get("colour") or labelled["colour"] or percent.get("colour") or token_colour
    )
    vehicle_type = positional.get("vehicleType") or labelled["vehicleType"] or token_vehicle_type

    confidence = "high" if (vin and plate and (make or expiry_date)) else "low"

    parsed: dict[str, Any] = {
        "licence_number": plate,
        "registering_authority": labelled["registeringAuthority"],
        "control_number": labelled["controlNumber"],
        "registration_number": labelled["registerNumber"],
        "make": make,
        "model": model,
        "colour": colour,
        "vin": vin,
        "engine_number": engine_number,
        "expiry_date": expiry_date,
        "tare_kg": _mass_to_float(tare),
        "gvm_kg": _mass_to_float(gvm),
        "vehicle_type": vehicle_type,
        "confidence": confidence,
        "raw_text": raw,
    }

    explained = _explained_token_indexes(tokens, raw, parsed)
    unparsed: dict[str, str] = {
        token: "unrecognised"
        for index, token in enumerate(tokens)
        if index not in explained
    }
    for identifier in positional.get("positionalIdentifiers", []):
        used = {plate.strip().upper(), (labelled["registerNumber"] or "").strip().upper()}
        if identifier.strip().upper() in used:
            continue  # this one is accounted for: it is the plate/registration we kept
        unparsed[identifier] = (
            "unassigned disc identifier — which of these fields is the NaTIS registration "
            "number and which is the licence number still needs the printed disc face"
        )
    parsed["unparsed_fields"] = unparsed
    return parsed


def is_disc_parseable(parsed: Mapping[str, Any]) -> bool:
    """True when at least one real disc field came out of a payload."""
    return any(str(parsed.get(key) or "").strip() for key in DISC_FIELD_KEYS)


# ── Engine layer ────────────────────────────────────────────────────────────

#: Measured default (see docs/plans/disc-decode-findings.md): on the REAL disc photograph both
#: engines decode on the *original* variant, and zxing-cpp does it in 22 ms from a 2 MB wheel
#: while pdf417decoder needs 251 ms and drags in numpy + opencv-python (~115 MB installed).
#: zxing-cpp missed only two driver's-licence-card samples, which are not ABI's use case. So
#: zxing-cpp is primary; pdf417decoder stays supported as an optional second opinion (the code
#: skips an engine that is not installed, and requirements.txt does not ship it).
DEFAULT_ENGINE_ORDER: tuple[str, ...] = ("zxing-cpp", "pdf417decoder")


def _engine_zxing_cpp(image: Any) -> list[str]:
    import zxingcpp  # imported lazily: a missing engine must not break app import

    results = zxingcpp.read_barcodes(image, formats=zxingcpp.BarcodeFormat.PDF417)
    return [result.text for result in results if getattr(result, "text", "")]


def _engine_pdf417decoder(image: Any) -> list[str]:
    from pdf417decoder import PDF417Decoder  # type: ignore[import-not-found]

    decoder = PDF417Decoder(image.convert("RGB"))
    decoder.decode()
    payloads: list[str] = []
    for payload in getattr(decoder, "barcodes_data", None) or []:
        raw = bytes(payload)
        # Disc payloads are plain text; a binary payload here means a driver's licence card,
        # which is a different (RSA) path this module deliberately does not handle.
        payloads.append(raw.decode("utf-8", "replace"))
    return payloads


_ENGINES: Mapping[str, Callable[[Any], list[str]]] = {
    "zxing-cpp": _engine_zxing_cpp,
    "pdf417decoder": _engine_pdf417decoder,
}

#: Variant ladder — the plan's minimum (original, grayscale, contrast, 2x, top crop, rotate 90)
#: plus the extra attempts the proven archive decoder needed on glare-heavy phone photos.
VARIANT_NAMES: tuple[str, ...] = (
    "original",
    "grayscale",
    "contrast-1.8",
    "contrast-2.5",
    "upscale-150",
    "upscale-2x",
    "upscale-3x-gray-contrast",
    "topcrop-40",
    "middlecrop-70",
    "rotate90",
    "rotate270",
)


def image_variants(image: Any) -> list[tuple[str, Any]]:
    """Decode attempts from least to most destructive (ported from the proven decoder)."""
    from PIL import ImageEnhance, ImageOps

    rgb = image.convert("RGB")
    gray = ImageOps.grayscale(rgb)
    width, height = rgb.size
    return [
        ("original", rgb.copy()),
        ("grayscale", gray.copy()),
        ("contrast-1.8", ImageEnhance.Contrast(gray.copy()).enhance(1.8)),
        ("contrast-2.5", ImageEnhance.Contrast(gray.copy()).enhance(2.5)),
        ("upscale-150", rgb.resize((round(width * 1.5), round(height * 1.5)))),
        ("upscale-2x", rgb.resize((width * 2, height * 2))),
        (
            "upscale-3x-gray-contrast",
            ImageEnhance.Contrast(
                ImageOps.grayscale(rgb.resize((width * 3, height * 3)))
            ).enhance(2.0),
        ),
        ("topcrop-40", rgb.crop((0, 0, width, round(height * 0.40)))),
        ("middlecrop-70", rgb.crop((0, round(height * 0.15), width, round(height * 0.85)))),
        ("rotate90", rgb.rotate(90, expand=True)),
        ("rotate270", rgb.rotate(270, expand=True)),
    ]


def _load_image(data: bytes) -> Any:
    from PIL import Image, UnidentifiedImageError

    try:
        image = Image.open(io.BytesIO(data))
        image.load()
        return image
    except (UnidentifiedImageError, OSError, ValueError) as exc:
        raise DiscDecodeError(
            DiscErrorKind.IMAGE_UNREADABLE,
            "That file is not a readable image. Try a JPEG or PNG photo of the disc.",
            detail=str(exc),
        ) from exc


def decode_disc_image(
    data: bytes,
    *,
    engines: Sequence[str] | None = None,
    variants: Iterable[tuple[str, Any]] | None = None,
) -> list[str]:
    """Decode the PDF417 barcode(s) on a licence-disc photo.

    Returns the raw payload strings (usually one). Raises :class:`DiscDecodeError` with
    ``kind == DiscErrorKind.NO_BARCODE`` when no engine finds a barcode in any variant — the UI
    must show a *different* message for that than for a payload that decoded but held no fields
    (:func:`decode_and_parse` raises ``UNPARSEABLE`` for the latter).
    """
    image = _load_image(data)
    engine_names = tuple(engines) if engines else DEFAULT_ENGINE_ORDER
    attempted: list[str] = []

    for engine_name in engine_names:
        engine = _ENGINES.get(engine_name)
        if engine is None:
            attempted.append(f"{engine_name}: unknown engine")
            continue
        candidates = list(variants) if variants is not None else image_variants(image)
        for variant_name, variant_image in candidates:
            try:
                payloads = engine(variant_image)
            except ImportError as exc:
                attempted.append(f"{engine_name}: not installed ({exc})")
                break
            except Exception as exc:  # noqa: BLE001 - a bad variant must not kill the scan
                attempted.append(f"{engine_name}/{variant_name}: {type(exc).__name__}: {exc}")
                continue
            found = [payload for payload in payloads if payload and payload.strip()]
            if found:
                return _dedupe(found)

    raise DiscDecodeError(
        DiscErrorKind.NO_BARCODE,
        "No barcode found on that photo. Move closer, keep the disc flat and avoid glare — "
        "or paste the barcode text / type the details in.",
        detail="; ".join(attempted[-4:]) if attempted else "no engines available",
    )


def decode_payloads(payloads: Sequence[str]) -> dict[str, Any]:
    """Parse already-decoded payloads, preferring the most confident result."""
    best: dict[str, Any] | None = None
    for payload in payloads:
        parsed = parse_disc_text(payload)
        if not is_disc_parseable(parsed):
            continue
        if parsed["confidence"] == "high":
            return parsed
        if best is None:
            best = parsed
    if best is None:
        raise DiscDecodeError(
            DiscErrorKind.UNPARSEABLE,
            "The barcode was read, but no licence-disc details could be recognised in it.",
            detail=f"{len(payloads)} payload(s) tried",
        )
    return best


def decode_and_parse(data: bytes, *, engines: Sequence[str] | None = None) -> dict[str, Any]:
    """Image bytes -> parsed disc fields, with the two failure kinds kept distinct."""
    payloads = decode_disc_image(data, engines=engines)
    return decode_payloads(payloads)


def _dedupe(values: Iterable[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for value in values:
        if value not in seen:
            seen.add(value)
            out.append(value)
    return out
