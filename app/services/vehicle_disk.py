VIN_RE = re.compile(r"\b([A-HJ-NPR-Z0-9]{17})\b", re.ASCII)
PLATE_RE = re.compile(
    r"\b([A-Z]{2,3}[\s-]?\d{1,6}[\s-]?[A-Z]{0,3}(?:\s?[A-Z]{2})?)\b", re.ASCII
)

_ISO_COMPACT_RE = re.compile(r"^(\d{4})(\d{2})(\d{2})$", re.ASCII)
_ISO_DASHED_RE = re.compile(r"^(\d{4})[/\-.](\d{2})[/\-.](\d{2})$", re.ASCII)
_LOCAL_DASHED_RE = re.compile(r"^(\d{2})[/\-.](\d{2})[/\-.](\d{4})$", re.ASCII)
_LOOSE_DATE_RE = re.compile(r"(\d{4})(\d{2})(\d{2})", re.ASCII)

