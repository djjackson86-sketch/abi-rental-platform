r"""NaTIS vehicle licence-disc decoding and parsing.

Programme phase 1 (feature A / A1) of the 2026-09-23 ABI programme.

Two jobs live here:

1. **image -> barcode payload(s)** — :func:`decode_disc_image`. The NaTIS vehicle licence
   disc barcode is a plain-text PDF417 (master plan decision D1: *not* RSA-encrypted, unlike
   a driver's licence card). Decoding is server-side so there is one code path for camera,
   file upload and paste; the engine choice is measured, not assumed — see
   ``docs/plans/disc-decode-findings.md``.
2. **payload text -> fields** — :func:`parse_disc_text`, a **faithful Python port of the
   already-shipping TrailerPro parser**
   (``/mnt/d/Claude/trailer-rental-app/src/lib/saDiscParser.ts``, 379 lines). Do not invent a
   second grammar: the port is asserted field-by-field against the real TypeScript output in
   ``tests/test_programme_20260923_vehicle_disk.py`` (fixtures regenerated by
   ``scripts/disc_parity_ts.mts``).

Deliberate differences from the reference, all documented, all additive:

* ``tare_kg`` / ``gvm_kg`` come back as ``float | None`` instead of the reference's strings,
  because the ``vehicles`` table stores REAL columns and a missing mass must be NULL, never 0.
* The label-value mass patterns require the number to *end* (``(\d{3,5})(?!\d)``) and the result
  is range-guarded to 300-80000 kg. Measured reference behaviour: ``GVM 1234567`` yields
  ``12345`` there because the regex takes the first five digits and checks nothing. D3 is "never
  invent a vehicle figure", so these guards only ever blank a nonsense value — they cannot
  produce one, and every well-formed disc is unaffected.
* ``registering_authority``, ``control_number`` and ``registration_number`` are surfaced. The
  reference already parses the first two into locals and the third as ``registerNumber``, but
  never exposes them; A1's spec asks for them.
* ``unparsed_fields`` (tokens carrying no signal the parser recognises — no label keyword, no
  number, no date, no known make/colour/type, no text that landed in a field) and ``raw_text``
  are returned so staff can eyeball anything that was not recognised before saving.

Known reference behaviour carried over unchanged (measured, see the findings doc): the
percent-delimited branch can assign the NaTIS registration number to ``engine_number`` when
that field appears before the engine number, and the documented "fixed-width positional"
layout is **not** actually parsed — a space-separated payload only yields plate/VIN/engine
through the top-level regexes. Both are recorded for Don rather than silently "fixed".

There is **no towing capacity and no GCM on a licence disk** (D3) — this module never
produces one.
"""

